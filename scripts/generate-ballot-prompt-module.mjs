import fs from "node:fs";
import path from "node:path";

const repoRoot = path.resolve(import.meta.dirname, "..");
const docsDir = path.join(repoRoot, "docs");
const generatedDir = path.join(repoRoot, "src", "lib", "generated");

// Locale discovery is convention-based so adding a prompt variant is
// data-only: docs/BALLOT_PROMPT.md is the base English prompt and
// docs/BALLOT_PROMPT_<CODE>.md (e.g. BALLOT_PROMPT_ES.md) adds locale
// <code>. Each yields src/lib/generated/ballotPrompt<Code>.generated.ts
// exporting BALLOT_PROMPT_<CODE>, plus one shared registry module
// (ballotPrompts.generated.ts) keyed by lowercase locale code.
const PROMPT_DOC_PATTERN = /^BALLOT_PROMPT(?:_([A-Za-z]{2,3}))?\.md$/;

function pascalCase(locale) {
  return locale.charAt(0).toUpperCase() + locale.slice(1).toLowerCase();
}

function discoverPrompts() {
  const prompts = [];
  for (const entry of fs.readdirSync(docsDir)) {
    const match = PROMPT_DOC_PATTERN.exec(entry);
    if (!match) continue;
    const locale = (match[1] ?? "en").toLowerCase();
    prompts.push({
      locale,
      docsPath: path.join(docsDir, entry),
      outputPath: path.join(
        generatedDir,
        `ballotPrompt${pascalCase(locale)}.generated.ts`,
      ),
      exportName: `BALLOT_PROMPT_${locale.toUpperCase()}`,
      moduleName: `ballotPrompt${pascalCase(locale)}.generated`,
      sourceLabel: `docs/${entry}`,
    });
  }
  // Deterministic output: base English first, then other locales A→Z.
  return prompts.sort((a, b) =>
    a.locale === "en"
      ? -1
      : b.locale === "en"
        ? 1
        : a.locale < b.locale
          ? -1
          : 1,
  );
}

function extractPrompt(docs) {
  const startMarker = "## The Prompt\n\n";
  const endMarker = "\n---\n\n## Share this";
  const startIndex = docs.indexOf(startMarker);
  const endIndex = docs.indexOf(endMarker);

  if (startIndex >= 0 && endIndex > startIndex) {
    return docs.slice(startIndex + startMarker.length, endIndex).trim();
  }

  return docs.trim();
}

const prompts = discoverPrompts();
if (prompts.length === 0) {
  throw new Error(`No docs/BALLOT_PROMPT*.md files found in ${docsDir}`);
}

fs.mkdirSync(generatedDir, { recursive: true });

for (const promptConfig of prompts) {
  const docs = fs.readFileSync(promptConfig.docsPath, "utf8");
  const prompt = extractPrompt(docs);
  const escapedPrompt = prompt
    .replaceAll("\\", "\\\\")
    .replaceAll("`", "\\`")
    .replaceAll("${", "\\${");

  const declarationPrefix = `export const ${promptConfig.exportName} =`;
  const firstLine = prompt.split("\n")[0] ?? "";
  const declaration =
    declarationPrefix.length + 1 + firstLine.length > 80
      ? `${declarationPrefix}\n  \`${escapedPrompt}\` as const;`
      : `${declarationPrefix} \`${escapedPrompt}\` as const;`;

  const output = `// Generated from ${promptConfig.sourceLabel} by scripts/generate-ballot-prompt-module.mjs
// Do not edit by hand.

${declaration}
`;

  fs.writeFileSync(promptConfig.outputPath, output);
}

// Registry module: maps every discovered locale to its prompt so consumers
// select variants by locale key instead of importing per-locale constants.
const registryImports = prompts
  .map((p) => `import { ${p.exportName} } from "./${p.moduleName}";`)
  .join("\n");
const registryEntries = prompts
  .map((p) => `  ${p.locale}: ${p.exportName},`)
  .join("\n");
const registryOutput = `// Generated by scripts/generate-ballot-prompt-module.mjs from docs/BALLOT_PROMPT*.md.
// Do not edit by hand. Add a locale by adding docs/BALLOT_PROMPT_<CODE>.md and
// re-running \`npm run sync:ballot-prompt\`.

${registryImports}

export const BALLOT_PROMPTS = {
${registryEntries}
} as const;

export type BallotPromptLocale = keyof typeof BALLOT_PROMPTS;
`;

fs.writeFileSync(
  path.join(generatedDir, "ballotPrompts.generated.ts"),
  registryOutput,
);
